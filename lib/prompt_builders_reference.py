"""参考生视频模式 Prompt 构建器。

设计原则与 prompt_builders_script.py 一致：
- 不重复 schema 已声明的枚举（type 等）；让 response_schema 直接约束。
- 多选枚举字段不在 prompt 里写"如何选"判据；让模型按画面内容自行决定。
- 字段说明给指导和 example，不堆"必须 / 禁止"清单。
- 跨 backend 时长 / references 上限通过参数显式注入，不在文本里硬编码秒数。

【本文件已做三类定向加固，修改处均有 MOD-N 注释锚点，搜索 MOD- 可跳转】
  MOD-1 ~ MOD-7：台词与剧情内容零删减（解除时长天花板、台词铁律前置、三条一票否决自检等）。
  MOD-8 ~ MOD-9：每个 shot 强制包含 @[场景]（维度补位、示例修正、references 保护、零缺失校验）。
  MOD-10 ~ MOD-15：时长自由化（取消「档位」概念、反机械凑时长、秒数回归剧情节奏台词）。
  三类加固均只改 prompt 文本，未改函数签名、参数、返回类型与输出 JSON 结构。

# >>> 时长自由化改造（MOD-10 ~ MOD-15）<<<
症状：模型把每个 unit 都凑到 max_duration（如 15 秒），且机械切成 5+5+5 三个等长镜头。
根因两层：
  (a) schema 层（已在 lib/script_models.py 修复）：unit 总时长曾被硬约束为
      supported_durations 的枚举成员，写 13 秒会被直接拒结，模型只能向整档值靠；
  (b) prompt 层（本文件）：把**单 shot** 的 duration 也描述成「只能取自 supported_durations
      档位」、反复说「向上取到最近的合法档位」——而 schema 其实允许 1-15 任意整数。
      两者叠加后，「用5/10/15 凑出 5/10/15」的最低阻力解就是 5+5+5=15。
本次 prompt 层修正：
- MOD-10 单 shot 时长从「档位选择」改为「1 至上限任意整数」，与 schema 真实口径对齐
- MOD-11 unit 总时长条款改为「≤ 上限」单一硬约束，并给出 7/9/13 秒等**正面示例**
- MOD-12 台词时长估算从「向上取到最近档位」改为「直接取算出的整数」
- MOD-13 差异化分配从「较短/中等/较长档位」改为具体秒数区间指引
- MOD-14 新增「反机械凑时长」一票否决自检（查凑满上限、查等长均分、查档位值偏好）
- MOD-15 复核清单与节奏条款同步去档位化

# >>> 台词保真改造（MOD-0 ~ MOD-7）<<<
本模式（reference_video）不像 narration / drama 那样走 ADR 0041 两段式，
shots[].text 由 LLM 全量生成，台词混在画面描述里 → 存在被压缩 / 概括 / 改写的结构性风险。
本版在不改动后端架构的前提下，用以下手段把「台词零删减」提到最高优先级：
- MOD-1 解除单 shot 1-5 秒硬天花板，长台词有合法时长可承载
- MOD-2 台词零删减升格为第 1 条绝对禁止（Prompt 开头，服从度最高）
- MOD-3 注入 step1 台词清单锚点与 max_duration / unit 拆分指引
- MOD-4 快节奏剪辑条款给含台词镜头开例外
- MOD-5 「严禁废话」限定为「禁止新增」，不再构成删除授权
- MOD-6 shots 划分以台词承载量为最高优先级依据
- MOD-7 复核清单最前面插入台词零遗漏 / 逐字一致硬校验
"""

